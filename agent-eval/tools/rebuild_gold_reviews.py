"""Validate actual-human review forms and prepare immutable Gold successors.

Blank forms may be generated by ``review_invoice_data.py export-batch``.  This
module never invents reviewer identity or decisions.  It only accepts complete
forms bound to exact current Gold and source bytes, then rebuilds every derived
Case/Benchmark pin in the controlled staging tree.  Publication remains the
separate ``rebuild_publication.py`` step.
"""
from copy import deepcopy
from datetime import datetime, timezone
import argparse
import hashlib
import json
from pathlib import Path
import re

from rebuild_case_release import canonical_digest
from rebuild_dataset import json_bytes


REVIEW_KEYS = {
    'schemaVersion', 'kind', 'assetKind', 'assetId', 'recordId', 'target',
    'reviewers', 'owner', 'decision', 'rationale', 'checks', 'evidence',
    'disputes', 'exposure', 'identityVerification', 'goldReview',
}
INNER_KEYS = {
    'schemaVersion', 'kind', 'sampleId', 'baseVersion', 'reviewers', 'coverage',
    'fieldReviews', 'extraFieldReviews', 'lineItemReviews', 'lineCountDecision',
    'replacementLineItems',
    'documentDecision', 'documentNotes', 'disputes', 'instructions',
}
DECISION_KEYS = {'decision', 'candidate', 'replacement', 'reviewNote'}
LINE_KEYS = {
    'lineId', 'rowOrdinal', 'originalRowLabel', 'decision', 'fields',
    'replacement', 'reviewNote',
}


def _need(condition, reason):
    if not condition:
        raise ValueError(reason)


def _text(value):
    return isinstance(value, str) and bool(value.strip())


def _exact(value, keys, label):
    _need(isinstance(value, dict) and set(value) == keys, f'{label} fields differ')


def _review_path(form):
    identity = form.get('assetId')
    _need(isinstance(identity, str) and re.fullmatch(r'[A-Za-z0-9_-]+', identity),
          'Unsafe reviewed sample identity')
    return f'manifests/reviews/gold-fresh-{identity}-{canonical_digest(form)}.json'


def _validate_reviewers(reviewers):
    from review_invoice_data import validate_reviewers
    validate_reviewers(reviewers, 'attestsContentReview')
    validate_reviewers(reviewers, 'attestsOriginalImageReview')


def _evidence_path(project, quality, entry):
    path = entry.get('path')
    _need(_text(path) and '..' not in Path(path).parts and not Path(path).is_absolute(),
          'Unsafe review evidence path')
    if path.startswith('data/invoices/voxel51/'):
        return Path(project) / path
    return Path(quality) / path


def _validate_evidence(project, quality, form, gold):
    evidence = form.get('evidence')
    _need(isinstance(evidence, list) and evidence, 'Review evidence is required')
    seen = set()
    for entry in evidence:
        _need(isinstance(entry, dict) and set(entry) == {'path', 'sha256', 'note'} and
              _text(entry['note']) and re.fullmatch(r'[a-f0-9]{64}', entry['sha256'] or ''),
              'Invalid review evidence entry')
        if entry['path'] == form['target']['path']:
            _need(entry['sha256'] == form['target']['sha256'],
                  'Reviewed Gold evidence differs from bound target')
        else:
            path = _evidence_path(project, quality, entry)
            _need(path.is_file() and hashlib.sha256(path.read_bytes()).hexdigest() == entry['sha256'],
                  'Review evidence bytes changed')
        seen.add(entry['path'])
    _need(form['target']['path'] in seen and gold['sourceEvidence']['original'] in seen,
          'Review must cite both exact Gold and original image')


def _reviewed_field(entry, base, reviewer_id):
    from rebuild_annotations import _field
    _exact(entry, DECISION_KEYS, 'field review')
    _need(entry['candidate'] == base, 'Field candidate differs from bound Gold')
    _need(entry['decision'] in {'accept', 'replace'}, 'Every field needs accept or replace')
    _need(_text(entry['reviewNote']), 'Every field decision needs a review note')
    value = deepcopy(base if entry['decision'] == 'accept' else entry['replacement'])
    _need(isinstance(value, dict), 'Replacement field is required')
    value.pop('review', None)
    _field(value)
    value['review'] = {'status': 'accepted', 'reviewer': reviewer_id}
    return value


def _reviewed_line_value(value, reviewer_id, ordinal):
    """Validate one human-supplied final line and add field review provenance."""
    from rebuild_annotations import HEADERS, LINE_FIELDS, _field, _identity
    _exact(value, {'lineId', 'rowOrdinal', 'originalRowLabel', 'fields'}, 'replacement line')
    _need(_identity(value['lineId']) and value['rowOrdinal'] == ordinal and
          (value['originalRowLabel'] is None or _text(value['originalRowLabel'])),
          'Replacement line identity or row order differs')
    fields = value['fields']
    _need(isinstance(fields, dict) and set(HEADERS).issubset(fields) and
          set(fields).issubset(LINE_FIELDS), 'Replacement line fields are incomplete')
    reviewed = {}
    for key, candidate in fields.items():
        field = deepcopy(candidate)
        field.pop('review', None)
        _field(field)
        field['review'] = {'status': 'accepted', 'reviewer': reviewer_id}
        reviewed[key] = field
    return {'lineId': value['lineId'], 'rowOrdinal': ordinal,
            'originalRowLabel': value['originalRowLabel'], 'fields': reviewed}


def validate_and_apply(project, quality, base, form):
    """Purely validate one filled form and return its Gold/record successor."""
    project, quality = Path(project).resolve(), Path(quality).resolve()
    _exact(form, REVIEW_KEYS, 'asset review')
    _need(form['schemaVersion'] == 1 and form['kind'] == 'human_asset_review' and
          form['assetKind'] == 'gold' and form['assetId'] == base['sampleId'],
          'Review identity differs from Gold')
    base_raw = json_bytes(base)
    expected_target = {'path': f'gold/{base["id"]}.json', 'bytes': len(base_raw),
                       'sha256': hashlib.sha256(base_raw).hexdigest()}
    _need(form['target'] == expected_target,
          'Review target differs from current Gold bytes')
    _need(form['identityVerification'] == 'submitter_attestation_only',
          'Unknown reviewer identity protocol')
    _validate_reviewers(form['reviewers'])
    _need(_text(form['recordId']) and re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]{0,100}', form['recordId']),
          'Review record identity is required')
    _need(_text(form['owner']) and _text(form['rationale']) and form['decision'] == 'accept',
          'Accepted review needs owner, rationale and explicit decision')
    expected_checks = {'sourceIntegrity', 'fieldCoverage', 'uncertainty', 'splitAndExposure'}
    _need(isinstance(form['checks'], dict) and set(form['checks']) == expected_checks and
          all(value is True for value in form['checks'].values()),
          'Gold content review checks are incomplete')
    exposure = form['exposure']
    _need(isinstance(exposure, dict) and exposure.get('reviewed') is True and
          _text(exposure.get('scope')) and _text(exposure.get('notes')),
          'Exposure review is incomplete')
    _need(isinstance(form['disputes'], list) and not any(
        isinstance(item, dict) and item.get('status') == 'open' for item in form['disputes']),
        'Open disputes block Gold acceptance')
    _validate_evidence(project, quality, form, base)

    review = form['goldReview']
    _exact(review, INNER_KEYS, 'fresh Gold review')
    _need(review['schemaVersion'] == 3 and review['kind'] == 'fresh_gold_human_review' and
          review['sampleId'] == base['sampleId'] and review['baseVersion'] == base['version'],
          'Fresh review base differs')
    _need(review['reviewers'] == form['reviewers'], 'Inner and outer reviewers differ')
    _need(isinstance(review['coverage'], dict) and set(review['coverage']) == {
        'originalImageReviewed', 'headerReviewed', 'lineItemsReviewed', 'totalsReviewed',
        'sourceParseCompared', 'uncertaintyReviewed'} and
        all(value is True for value in review['coverage'].values()),
        'Whole-invoice review coverage is incomplete')
    _need(review['lineCountDecision'] in {'accept', 'replace'} and
          review['documentDecision'] == 'accept' and _text(review['documentNotes']),
          'Line count and document decision must be accepted or explicitly replaced')
    _need(isinstance(review['disputes'], list) and not any(
        isinstance(item, dict) and item.get('status') == 'open' for item in review['disputes']),
        'Open document disputes block acceptance')
    _need(set(review['fieldReviews']) == set(base['fields']) and
          set(review['extraFieldReviews']) == set(base.get('extraFields', {})),
          'Reviewed field set differs from Gold')
    reviewer_id = form['reviewers'][0]['reviewerId']
    fields = {key: _reviewed_field(review['fieldReviews'][key], value, reviewer_id)
              for key, value in base['fields'].items()}
    extra = {key: _reviewed_field(review['extraFieldReviews'][key], value, reviewer_id)
             for key, value in base.get('extraFields', {}).items()}
    line_reviews = review['lineItemReviews']
    _need(isinstance(line_reviews, list) and len(line_reviews) == len(base['lineItems']),
          'Reviewed line count differs from Gold')
    lines = []
    for source, entry in zip(base['lineItems'], line_reviews):
        _exact(entry, LINE_KEYS, 'line review')
        _need((entry['lineId'], entry['rowOrdinal'], entry['originalRowLabel']) ==
              (source['lineId'], source['rowOrdinal'], source.get('originalRowLabel')) and
              entry['decision'] in {'accept', 'replace'} and _text(entry['reviewNote']) and
              set(entry['fields']) == set(source['fields']),
              'Line identity or decision differs')
        if entry['decision'] == 'replace':
            _need(isinstance(entry['replacement'], dict), 'Replaced line needs a complete replacement')
            revised_line = _reviewed_line_value(entry['replacement'], reviewer_id, len(lines) + 1)
        else:
            _need(entry['replacement'] is None, 'Accepted line cannot contain a replacement')
            revised_line = {key: deepcopy(source[key]) for key in
                            ('lineId', 'rowOrdinal', 'originalRowLabel')}
            revised_line['fields'] = {
                key: _reviewed_field(entry['fields'][key], value, reviewer_id)
                for key, value in source['fields'].items()}
        lines.append(revised_line)
    if review['lineCountDecision'] == 'replace':
        replacements = review['replacementLineItems']
        _need(isinstance(replacements, list), 'Replacement line list is required')
        lines = [_reviewed_line_value(value, reviewer_id, ordinal)
                 for ordinal, value in enumerate(replacements, 1)]
    else:
        _need(review['replacementLineItems'] is None,
              'Accepted line count cannot contain replacement lines')
    _need(len({line['lineId'] for line in lines}) == len(lines),
          'Final line identities must be unique')

    record_path = _review_path(form)
    revised = deepcopy(base)
    revised.update(
        version=base['version'] + 1,
        status='human_reviewed',
        humanVerified=True,
        reviewStatus='accepted',
        reviewedBy=[row['reviewerId'] for row in form['reviewers']],
        reviewedAt=form['reviewers'][-1]['reviewedAt'],
        acceptedGoldVersion=base['version'] + 1,
        eligibleForFieldScoring=True,
        formalAcceptanceEligible=False,
        fields=fields,
        extraFields=extra,
        lineItems=lines,
        humanReviewNotes=review['documentNotes'],
        reviewLevel='double_human' if len(form['reviewers']) == 2 else 'single_human',
        humanReviewRef={'path': record_path, 'sha256': canonical_digest(form),
                        'digestScope': 'canonical_human_review_form'},
        humanReviewParentRef={'id': base['id'], 'version': base['version'],
                              'sha256': canonical_digest(base)},
        blockingReasons=[reason for reason in base['blockingReasons']
                         if reason != 'human_review_required'],
    )
    revised['provenance'] = deepcopy(base['provenance'])
    revised['provenance'].update(humanReviewPerformed=True,
                                 humanReviewerIdentityProtocol='submitter_attestation_only')
    record = {'schemaVersion': 1, 'kind': 'fresh_gold_human_review_record',
              'id': form['recordId'], 'previousGold': deepcopy(base),
              'review': deepcopy(form), 'resultGoldSha256': canonical_digest(revised),
              'recordedAt': datetime.now(timezone.utc).isoformat(),
              'identityVerification': 'submitter_attestation_only',
              'formalAcceptanceEligible': False}
    return revised, record_path, record


def validate_human_review_record(current, files, project=None, quality=None):
    reference = current.get('humanReviewRef')
    _need(isinstance(reference, dict), 'Human review reference missing')
    path = reference.get('path')
    _need(isinstance(path, str) and path in files, 'Human review record missing')
    try:
        record = json.loads(files[path])
    except (TypeError, ValueError, UnicodeDecodeError) as error:
        raise ValueError('Invalid human review record') from error
    _exact(record, {'schemaVersion', 'kind', 'id', 'previousGold', 'review',
                    'resultGoldSha256', 'recordedAt', 'identityVerification',
                    'formalAcceptanceEligible'}, 'human review record')
    _need(record.get('schemaVersion') == 1 and
          record.get('kind') == 'fresh_gold_human_review_record' and
          record.get('id') == record.get('review', {}).get('recordId') and
          record.get('identityVerification') == 'submitter_attestation_only' and
          record.get('formalAcceptanceEligible') is False,
          'Unknown or inconsistent human review record')
    previous, form = record.get('previousGold'), record.get('review')
    if project is None or quality is None:
        # Replay validation still needs the immutable source/Gold bytes.  Infer
        # the repository root only for the standard controlled staging layout.
        project = Path(__file__).resolve().parents[2]
        quality = project / 'data/.preparation-stage/rebuild'
        if not quality.exists():
            quality = project / 'agent-eval/data'
    revised, expected_path, _ = validate_and_apply(project, quality, previous, form)
    _need(expected_path == path and revised == current and
          reference.get('sha256') == canonical_digest(form) and
          record.get('resultGoldSha256') == canonical_digest(current),
          'Gold differs from recorded human review')
    return previous


def _read_json(path):
    try:
        return json.loads(Path(path).read_text(encoding='utf-8-sig'))
    except (OSError, UnicodeDecodeError, ValueError) as error:
        raise ValueError(f'Cannot read review asset: {path}') from error


def load_review_batch(project, batch, snapshot):
    """Load a complete external batch and bind every form to current Gold bytes."""
    project, batch = Path(project).resolve(), Path(batch).resolve()
    quality = project / 'data/.preparation-stage/rebuild'
    _need(batch.is_dir() and not batch.is_relative_to(project / 'agent-eval/data'),
          'Review batch must be an external directory')
    index = _read_json(batch / 'index.json')
    _exact(index, {'schemaVersion', 'kind', 'materialSha256', 'goldCount',
                   'humanReviewsPerformed', 'instructions', 'items'}, 'review batch')
    _need(index['schemaVersion'] == 1 and index['kind'] == 'fresh_gold_human_review_batch' and
          index['goldCount'] == 100 and len(index['items']) == 100,
          'Review batch must describe all 100 fresh Gold candidates')
    forms, seen = [], set()
    for item in index['items']:
        _need(isinstance(item, dict) and set(item) == {
            'sampleId', 'split', 'goldTarget', 'form', 'originalPath',
            'originalSha256', 'fieldCount', 'lineCount', 'status'},
            'Review batch item fields differ')
        sample, relative = item['sampleId'], item['form']
        _need(_text(sample) and sample not in seen and isinstance(relative, str) and
              not Path(relative).is_absolute() and '..' not in Path(relative).parts,
              'Unsafe or duplicate review batch item')
        seen.add(sample)
        form = _read_json(batch / relative)
        gold_path = f'gold/gold-fresh-{sample}.json'
        _need(gold_path in snapshot, 'Review batch Gold is absent from current candidate')
        base = json.loads(snapshot[gold_path])
        _need(form.get('assetId') == sample and form.get('target') == item['goldTarget'] and
              form['target']['path'] == gold_path and form['target']['sha256'] == hashlib.sha256(
                  snapshot[gold_path]).hexdigest() and form['target']['bytes'] == len(snapshot[gold_path]),
              'Review form does not bind the exact current Gold')
        _need(item['split'] == base['split'] and item['originalPath'] == base['sourceEvidence']['original'] and
              item['fieldCount'] == len(base['fields']) + len(base.get('extraFields', {})) and
              item['lineCount'] == len(base['lineItems']),
              'Review batch metadata differs from current Gold')
        original_pin = next((pin for pin in base['sourceSnapshot']
                             if pin['path'].endswith('/original.jpg')), None)
        _need(original_pin and item['originalSha256'] == original_pin['sha256'],
              'Review batch original-image pin differs')
        forms.append((gold_path, base, form))
    _need(len(seen) == 100, 'Review batch identities are incomplete')
    return index, forms, quality


def inspect_review_batch(project, batch):
    """Validate bindings and report form completion without granting review status."""
    from rebuild_staging import read_candidate, snapshot_digest
    snapshot = read_candidate(project)
    index, forms, quality = load_review_batch(project, batch, snapshot)
    accepted, pending, invalid = 0, 0, []
    for _, base, form in forms:
        if form.get('decision') == 'pending':
            pending += 1
            continue
        try:
            validate_and_apply(project, quality, base, form)
            accepted += 1
        except ValueError as error:
            invalid.append({'sampleId': base['sampleId'], 'error': str(error)})
    return {
        'batchMaterialSha256': index['materialSha256'],
        'currentCandidateSha256': snapshot_digest(snapshot),
        'exactDatasetDigestMatch': index['materialSha256'] == snapshot_digest(snapshot),
        'forms': len(forms), 'acceptedHumanReviews': accepted,
        'pendingHumanReviews': pending, 'invalidHumanReviews': invalid,
        'candidateChanged': False, 'actualProductRuns': 0,
    }


def prepare_human_reviews(project, batch):
    """Apply all 100 completed reviews and atomically rebuild every derived pin."""
    from rebuild_case_release import assemble_case_files
    from rebuild_cases import compile_scenarios
    from rebuild_contracts import load_spec_contracts
    from rebuild_coverage_review import build_revision as refresh_coverage_and_benchmarks
    from rebuild_dataset import json_bytes, verify_asset_snapshot
    from rebuild_extraction import build_extraction_cases
    from rebuild_fixtures import registered_scenarios
    from rebuild_grader_review import refresh_existing as refresh_grader_receipt
    from rebuild_staging import (candidate_lock, read_candidate,
                                 revise_human_review_candidate, snapshot_digest)

    project = Path(project).resolve()
    with candidate_lock(project):
        snapshot = read_candidate(project)
        verify_asset_snapshot(project, snapshot, require_current_authors=False)
    index, forms, quality = load_review_batch(project, batch, snapshot)
    outputs = dict(snapshot)
    records = []
    for gold_path, base, form in forms:
        _need(form.get('decision') == 'accept',
              f'{base["sampleId"]}: all 100 reviews must be completed and accepted before preparation')
        revised, record_path, record = validate_and_apply(project, quality, base, form)
        _need(record_path not in outputs, 'Review record already exists in the candidate')
        outputs[gold_path] = json_bytes(revised)
        outputs[record_path] = json_bytes(record)
        records.append(record_path)

    contracts = load_spec_contracts(project)
    golds = [json.loads(data) for path, data in sorted(outputs.items()) if path.startswith('gold/')]
    cases = compile_scenarios(list(registered_scenarios().values()), contracts)
    cases += build_extraction_cases(golds, contracts)
    outputs = assemble_case_files(outputs, cases, contracts)
    outputs = refresh_grader_receipt(project, outputs)
    outputs = refresh_coverage_and_benchmarks(project, outputs)
    verify_asset_snapshot(project, outputs)
    result = revise_human_review_candidate(project, snapshot, outputs)
    result.update(
        batchMaterialSha256=index['materialSha256'],
        candidateSha256=snapshot_digest(outputs),
        acceptedHumanReviews=len(records),
        totalHumanVerifiedGold=sum(gold.get('humanVerified') is True for gold in golds),
        actualProductRuns=0,
        formalAcceptanceEligible=False,
        activeDatasetChanged=False,
    )
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['inspect', 'prepare'])
    parser.add_argument('--project', type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument('--batch', type=Path, required=True)
    args = parser.parse_args()
    result = (inspect_review_batch(args.project, args.batch) if args.command == 'inspect'
              else prepare_human_reviews(args.project, args.batch))
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
