"""Exact fresh business dependencies and declared input-only changes.

Base assets are generated by the fresh author, never read from legacy material.
Projection validates a supplied frozen asset; it never silently chooses latest.
Faults, approvals, verdicts and review metadata are not product input. Intentional
business conflicts stay visible and are not repaired by this materializer.
"""
from copy import deepcopy
import hashlib
import json
from pathlib import Path
import re
import stat

from rebuild_business import build_business_packages, validate_business

INPUT_KEYS = {'invoice', 'suppliers', 'purchaseOrders', 'goodsReceipts',
              'contracts', 'balances', 'historicalEntries'}


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(',', ':'), allow_nan=False).encode()).hexdigest()


def authored_business(contracts):
    from rebuild_bindings import bind_business
    return {asset['id']: bind_business(asset, contracts) for asset in build_business_packages()}


def asset_ref(asset):
    if (not isinstance(asset, dict) or not isinstance(asset.get('id'), str) or
            not re.fullmatch(r'business-[a-z0-9-]+', asset['id']) or
            type(asset.get('version')) is not int or asset['version'] < 1):
        raise ValueError('Business asset needs a safe identity and positive integer version')
    return {'id': asset['id'], 'version': asset['version'],
            'path': 'business/' + asset['id'] + '.json', 'assetSha256': digest(asset)}


def validate_reference(reference):
    if (not isinstance(reference, dict) or
            set(reference) != {'id', 'version', 'path', 'assetSha256'} or
            not isinstance(reference.get('id'), str) or
            not re.fullmatch(r'business-[a-z0-9-]+', reference['id']) or
            type(reference.get('version')) is not int or reference['version'] < 1 or
            reference.get('path') != 'business/' + reference['id'] + '.json' or
            not isinstance(reference.get('assetSha256'), str) or
            not re.fullmatch(r'[a-f0-9]{64}', reference['assetSha256'])):
        raise ValueError('Business reference has an invalid identity, version, path or digest')


def load_business(root, reference):
    """Read the exact local dependency without fallback or link traversal."""
    validate_reference(reference)
    root = Path(root).resolve()
    path = root
    for part in reference['path'].split('/'):
        path = path / part
        try:
            info = path.lstat()
        except OSError as exc:
            raise ValueError('Business dependency is missing or unreadable') from exc
        if path.is_symlink() or getattr(info, 'st_file_attributes', 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT:
            raise ValueError('Business dependency cannot traverse links or junctions')
    if not path.resolve().is_relative_to(root) or not path.is_file():
        raise ValueError('Business dependency is not a contained file')
    try:
        asset = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, UnicodeError, ValueError) as exc:
        raise ValueError('Business dependency is unreadable JSON') from exc
    if reference != asset_ref(asset):
        raise ValueError('Business dependency digest or identity differs')
    return asset


def validate_case_business(case, asset, contracts):
    """Close a Case's asset, specification and use-group references."""
    ref = case.get('businessRef')
    project_business(ref, asset, case.get('businessPatches'))
    pins = [{k: contracts['documents'][name][k] for k in ('path', 'bytes', 'sha256')}
            for name in ('product', 'evaluation')]
    if asset.get('specRefs') != pins:
        raise ValueError('Business source specification references differ')
    if (case.get('split') != asset['split'] or case.get('leakageGroup') != asset['leakageGroup'] or
            case.get('inputMode') != 'controlled_business_episode' or
            case.get('initialEnvironment', {}).get('fixtureBaseRef') != ref):
        raise ValueError('Business Case data use, group or environment differs')


def _segments(path):
    if not isinstance(path, str) or not path.startswith('/') or '~' in path or '\\' in path:
        raise ValueError('Business patch needs a simple exact JSON pointer')
    parts = path[1:].split('/')
    if len(parts) < 2 or parts[0] not in INPUT_KEYS or any(not p or p in {'.', '..'} for p in parts):
        raise ValueError('Business patch must address a field/row within allowed input')
    return parts


def _index(node, part, *, append=False):
    if isinstance(node, dict):
        return part
    if isinstance(node, list):
        if append and part == '-':
            return len(node)
        if not re.fullmatch(r'0|[1-9][0-9]*', part):
            raise ValueError('Business patch array index is invalid')
        index = int(part)
        if index >= len(node):
            raise ValueError('Business patch array index is absent')
        return index
    raise ValueError('Business patch traverses a scalar')


def apply_patches(data, patches):
    from rebuild_cases import assert_product_projection
    if not isinstance(patches, list):
        raise ValueError('Business patches must be a list')
    output = deepcopy(data)
    for patch in patches:
        if not isinstance(patch, dict) or patch.get('op') not in {'add', 'replace', 'remove'}:
            raise ValueError('Unknown business patch operation')
        expected = {'op', 'path', 'reason'} | ({'value'} if patch['op'] != 'remove' else set())
        if set(patch) != expected or not isinstance(patch['reason'], str) or not patch['reason'].strip():
            raise ValueError('Business patch needs exact configuration and a reason')
        parts = _segments(patch['path'])
        node = output
        for part in parts[:-1]:
            key = _index(node, part)
            if isinstance(node, dict) and key not in node:
                raise ValueError('Business patch parent is absent')
            node = node[key]
        key = _index(node, parts[-1], append=patch['op'] == 'add')
        if patch['op'] != 'remove':
            assert_product_projection(patch['value'])
            digest(patch['value'])  # Reject non-JSON/nonfinite values before mutation.
        if isinstance(node, dict):
            if (patch['op'] == 'add') == (key in node):
                raise ValueError('Business patch add needs absent key; replace/remove need existing key')
            if patch['op'] == 'remove':
                del node[key]
            else:
                node[key] = deepcopy(patch['value'])
        elif patch['op'] == 'add':
            node.insert(key, deepcopy(patch['value']))
        elif patch['op'] == 'remove':
            del node[key]
        else:
            node[key] = deepcopy(patch['value'])
    assert_product_projection(output)
    return output


def project_business(reference, asset, patches):
    """Admit the exact asset against current specifications before projection.

    The authority is the project containing this implementation, never cwd,
    a caller-owned materialization root, Case pins, or an asset's spec path.
    Keep the existing three-argument API; read current bytes on every admission
    so an earlier successful projection cannot authorize a stale specification.
    """
    validate_reference(reference)
    if reference != asset_ref(asset):
        raise ValueError('Business identity/version/digest differs from frozen reference')
    from rebuild_contracts import load_spec_contracts
    contracts = load_spec_contracts(Path(__file__).resolve().parents[2])
    pins = [{k: contracts['documents'][name][k] for k in ('path', 'bytes', 'sha256')}
            for name in ('product', 'evaluation')]
    if asset.get('specRefs') != pins:
        raise ValueError('Business source specification references differ')
    if (asset.get('schemaVersion') != 3 or asset.get('kind') != 'synthetic_business' or
            type(asset.get('version')) is not int or asset['version'] < 1 or
            asset.get('provenance', {}).get('legacyAssetsRead') != [] or
            not re.fullmatch(r'business-[a-z0-9-]+', asset.get('id', ''))):
        raise ValueError('Fresh business construction contract required')
    errors = validate_business(asset)
    if errors:
        raise ValueError('Invalid base business relationships: ' + ', '.join(errors))
    expected = authored_business(contracts).get(asset['id'])
    if asset != expected:
        raise ValueError('Business differs from its current authored revision')
    if set(asset.get('input', {})) != INPUT_KEYS:
        raise ValueError('Unknown or missing business input sections')
    # Validate base, then preserve explicitly introduced mismatches. Never use
    # baseline arithmetic validation to erase a case's declared failure condition.
    data = apply_patches(asset['input'], patches)
    return {'input': data, 'policy': deepcopy(asset['policy']),
            'initialState': deepcopy(asset['initialState']), 'appliedPatches': deepcopy(patches),
            'baseContentReviewed': False,
            'businessRef': deepcopy(reference), 'actualProductRun': False}
